use clap::{Parser, Subcommand};
use serde::{Deserialize, Serialize};
use std::fs;
use std::path::{Path, PathBuf};

#[derive(Parser, Debug)]
#[command(
    name = "xtask",
    about = "CAFramework internal developer and scaffolding tool"
)]
struct Cli {
    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand, Debug)]
enum Commands {
    /// Generate application icons from base SVG
    GenerateIcons,

    /// Codegen frontend and Rust files from app.toml
    Codegen {
        #[arg(short, long, default_value = "app.toml")]
        config: PathBuf,
        #[arg(long)]
        check: bool,
    },
    /// Scaffold a new app from CAFramework base template
    NewApp {
        #[arg(short, long, default_value = "app.toml")]
        config: PathBuf,
        #[arg(short, long)]
        out: PathBuf,
        #[arg(long)]
        with_sample: bool,
        #[arg(long)]
        dry_run: bool,
    },
    /// Run CI quality and architecture guards
    Guard {
        #[arg(long)]
        only: Option<String>,
    },
    /// Validate app.toml config schema
    Check {
        #[arg(short, long, default_value = "app.toml")]
        config: PathBuf,
    },
    /// Run local GCC Billing Hub mock server
    GccMock {
        #[arg(short, long, default_value_t = 8888)]
        port: u16,
    },
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AppConfig {
    pub app: AppMeta,
    pub window: WindowConfig,
    pub security: SecurityConfig,
    pub modules: ModulesConfig,
    pub roles: RolesConfig,
    pub menus: Vec<MenuItem>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AppMeta {
    pub name: String,
    pub slug: String,
    pub bundle_id: String,
    pub version: String,
    pub accent_color: String,
    pub error_prefix: String,
    pub description: String,
}

